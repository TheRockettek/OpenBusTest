#!/usr/bin/env bash
set -euo pipefail

export OPENBUS_OMSI_ROOT="/home/rock/.local/share/Steam/steamapps/common/OMSI 2"
if [[ "${OPENBUS_BENCHMARK:-0}" == "1" ]]; then
    export OPENBUS_BUS_CONFIG="${OPENBUS_BUS_CONFIG:-Vehicles/MAN_DL05/MAN_DL05.bus}"
    export OPENBUS_MODEL_CONFIG="${OPENBUS_MODEL_CONFIG:-Vehicles/MAN_DL05/Model/DL05.cfg}"
fi
export OPENBUS_MAP_PATH=Cotterell
export OPENBUS_MAP_TRAFFIC_DENSITY_MULTIPLIER=10.0
export OPENBUS_VSYNC=off
export OPENBUS_MAP_AI_COUNT=1000
export OPENBUS_MAP_BUS_COUNT=20
export OPENBUS_MAP_HUMAN_COUNT=1
export OPENBUS_MAP_TRAFFIC_DENSITY_MULTIPLIER=100
export OPENBUS_REFLECTION_TRANSPARENT=1
export OPENBUS_MATERIAL_BATCHING=1
export OPENBUS_REFLECTION_MAX_FPS=60
export OPENBUS_FRUSTUM_CULLING=1
export OPENBUS_WHEELS_FROM_ODE=0
export OPENBUS_SCRIPT_BACKEND=native
export OPENBUS_SCRIPT_HZ=60
export OPENBUS_ASSET_WORKERS=4
export OPENBUS_DOPPLER=1
export OPENBUS_CAPTURE_VIEWS=
export OPENBUS_CULLING_BACKEND=compute-indirect
export OPENBUS_STEERING_SMOOTHING=1

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD_DIR="${BUILD_DIR:-${ROOT_DIR}/build-linux}"

cd "$ROOT_DIR"
cmake -S . -B "$BUILD_DIR" -DCMAKE_BUILD_TYPE=Release -DOPENBUS_ENABLE_PERF_TRACE=OFF
cmake --build "$BUILD_DIR" --target OpenBus --parallel

export OPENBUS_VSYNC="${OPENBUS_VSYNC:-off}"
exec "$BUILD_DIR/OpenBus"
