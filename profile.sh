#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD_DIR="${BUILD_DIR:-${ROOT_DIR}/build-linux}"

cd "$ROOT_DIR"
cmake -S . -B "$BUILD_DIR" -DCMAKE_BUILD_TYPE=Release -DOPENBUS_ENABLE_PERF_TRACE=ON
cmake --build "$BUILD_DIR" --target OpenBus --parallel

export OPENBUS_OMSI_ROOT="/home/rock/.local/share/Steam/steamapps/common/OMSI 2"

export OPENBUS_BUS_CONFIG=Vehicles/MAN_DL05/MAN_DL05.bus
export OPENBUS_MODEL_CONFIG=Vehicles/MAN_DL05/Model/DL05.cfg
export OPENBUS_MAP_PATH=DBC_Map
export OPENBUS_MAP_SPAWN=1
export OPENBUS_VSYNC=off
export OPENBUS_MAP_AI_COUNT=500
export OPENBUS_MAP_BUS_COUNT=20
export OPENBUS_MAP_HUMAN_COUNT=1
export OPENBUS_MAP_TRAFFIC_DENSITY_MULTIPLIER=1
export OPENBUS_MATERIAL_BATCHING=1
export OPENBUS_REFLECTION_SIZE=1024
export OPENBUS_REFLECTION_INTERVAL=4
export OPENBUS_REFLECTION_TRANSPARENT=1
export OPENBUS_FRUSTUM_CULLING=1
export OPENBUS_WHEELS_FROM_ODE=0
export OPENBUS_SCRIPT_BACKEND=native
export OPENBUS_SCRIPT_HZ=60
export OPENBUS_ASSET_WORKERS=4
export OPENBUS_DOPPLER=1
export OPENBUS_TRACE=1
export OPENBUS_TRACE_FILE=openbus_trace.json
export OPENBUS_TRACE_MAX_EVENTS=10000000
export OPENBUS_TRACE_MIN_US=1
export OPENBUS_CULLING_BACKEND=compute-indirect
export OPENBUS_MAP_AI_SPAWN_DIAGNOSTICS=1

export OPENBUS_MAP_AI_SPAWN_VISIBLE=1

exec "$BUILD_DIR/OpenBus"
